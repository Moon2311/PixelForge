"""Load balancer checks against the running Compose stack.

Run with ``LB_TEST_URL=http://localhost:8000 uv run manage.py test
apps.common.tests_lb``; skipped when LB_TEST_URL is unset. Stopping an
instance (unhealthy upstream) is scripted in scripts/lb/check_lb.sh, which
needs Docker.
"""

import json
import os
import unittest
import urllib.request
from collections import Counter

from django.test import SimpleTestCase

LB_URL = os.environ.get("LB_TEST_URL", "").rstrip("/")


def get(path, headers=None):
    request = urllib.request.Request(f"{LB_URL}{path}", headers=headers or {})
    with urllib.request.urlopen(request, timeout=10) as response:
        return response.status, dict(response.headers), json.loads(response.read() or b"null")


@unittest.skipUnless(LB_URL, "set LB_TEST_URL to test the running load balancer")
class LoadBalancerTest(SimpleTestCase):
    def test_requests_are_spread_over_several_instances(self):
        served = Counter(get("/api/health/")[2]["data"]["instance"] for _ in range(30))
        self.assertGreaterEqual(len(served), 2, served)
        # least_conn on idle instances ends up close to round robin.
        self.assertGreater(min(served.values()), 5, served)

    def test_every_instance_serves_the_same_api(self):
        # Consecutive requests alternate between the instances (see above),
        # so these 20 responses come from all of them.
        bodies = set()
        for _ in range(20):
            status, _, body = get("/api/categories/")
            self.assertEqual(status, 200)
            bodies.add(json.dumps(body["data"], sort_keys=True))
        self.assertEqual(len(bodies), 1)

    def test_headers(self):
        status, headers, _ = get("/api/health/", {"X-Request-ID": "lbtest-0123456789"})
        self.assertEqual(status, 200)
        self.assertEqual(headers.get("X-Request-ID"), "lbtest-0123456789")  # correlation id passed through
        self.assertEqual(headers.get("Server"), "nginx")  # no version (server_tokens off)
        _, headers, _ = get("/api/health/")
        self.assertRegex(headers.get("X-Request-ID", ""), r"^[0-9a-f]{32}$")  # generated by nginx

    def test_internal_health_endpoint_is_not_public(self):
        with self.assertRaises(urllib.error.HTTPError) as caught:
            get("/nginx-health")
        self.assertEqual(caught.exception.code, 403)
